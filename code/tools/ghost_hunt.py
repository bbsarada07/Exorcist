"""Write docs/GHOST_HUNT.md: ghost census + 5 seeded-random false-COMPLETE cases walked from request to finding.

    python code/tools/ghost_hunt.py [--seed 2026]

No gold labels are used: the population is every evaluation case where the workflow reported COMPLETE and the
reconstruction says INCOMPLETE. The 5 cases are drawn with random.Random(seed).sample, not chosen by hand.
"""
from __future__ import annotations

import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from audit.config import CODE_DIR, DATASET_DIR  # noqa: E402
from audit.evidence_cards import CardBuilder  # noqa: E402
from audit.pipeline import AuditEngine  # noqa: E402
from audit.sidecars import ghost_census  # noqa: E402
from audit.walkthrough import GHOST_TYPES, eval_ids, walkthrough  # noqa: E402

PICKS = 5


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=2026)
    args = ap.parse_args()
    engine = AuditEngine(DATASET_DIR)
    results = engine.run()
    ids = eval_ids(engine)
    census = ghost_census(results, ids)
    population = [c for c in ids if results[c].case.reported_status == "COMPLETE" and results[c].status == "INCOMPLETE"]
    picks = random.Random(args.seed).sample(population, PICKS)
    drift_any = sum(1 for c in ids for a in results[c].assessments if a.status == "violation" and a.drift)
    drift_cases = sum(1 for c in ids if any(a.status == "violation" and a.drift for a in results[c].assessments))

    g, cw = census["ghosts_by_type"], census["cases_with_type"]
    out = ["# Ghost hunt", "",
           "A **ghost** is one violation the deletion workflow left behind: personal data that still exists, is still",
           "exposed, or can come back. This page uses no gold labels. It takes every evaluation case where the workflow",
           f"reported **COMPLETE** but the evidence reconstruction says **INCOMPLETE** ({len(population)} of "
           f"{sum(1 for c in ids if results[c].case.reported_status == 'COMPLETE')} COMPLETE claims), types every ghost, "
           "and walks five randomly drawn cases from the request to each finding.", "",
           f"Generated by `python code/tools/ghost_hunt.py --seed {args.seed}`; the same numbers are in "
           "`code/out/ghosts.json`, and each finding's full evidence card is in `code/out/findings_evidence.jsonl`.", "",
           "## Ghost types", "",
           "| Type | Rule that produces it |", "|---|---|",
           "| leftover record | REPORT_REMAINING_RECORD: a record the policy says to delete is still present |",
           "| replica drift | REPORT_REMAINING_RECORD where a snapshot shows the record gone from one copy but alive in another (replica, failover, region) |",
           "| exposed PII in a retained record | REPORT_EXPOSED_PII: a record policy keeps (redact / anonymise / tombstone) still shows direct identifiers |",
           "| active sync | REPORT_ACTIVE_DATA_FLOW: a connector that carries the subject's data is still enabled |",
           "| restore risk | REPORT_RESTORE_RISK: a backup holding the subject's data can still be restored |", "",
           "Each ghost has exactly one type. Replica drift is assigned only to leftover records. "
           f"Counted on any violation, drift touches {drift_any} ghosts in {drift_cases} cases "
           "(the `hidden_replica_drift` failure mode in lie_report.json), because exposed-PII records can drift too.", "",
           "## Counts", "",
           "| Ghost type | false-COMPLETE cases: ghosts | cases | all 355 INCOMPLETE of 518: ghosts | cases |",
           "|---|---:|---:|---:|---:|"]
    for t in GHOST_TYPES:
        out.append(f"| {t} | {g['false_COMPLETE'][t]} | {cw['false_COMPLETE'][t]} | {g['all_incomplete'][t]} | {cw['all_incomplete'][t]} |")
    out.append(f"| **total** | **{sum(g['false_COMPLETE'].values())}** | {census['cases']['false_COMPLETE']} | "
               f"**{sum(g['all_incomplete'].values())}** | {census['cases']['all_incomplete']} |")
    out += ["", f"{census['resurrected_ghosts']} ghosts were brought back by a sync or restore job after deletion "
            "(a `repopulated downstream resource` activity before audit_at).",
            f"The {sum(1 for c in ids if results[c].status == 'COMPLETE')} cases reconstructed as COMPLETE and the "
            f"{sum(1 for c in ids if results[c].status == 'NOT_APPLICABLE')} NOT_APPLICABLE requests have no ghosts by definition.",
            "", "By what the workflow reported:", "", "| Reported | " + " | ".join(GHOST_TYPES) + " |",
            "|---|" + "---:|" * len(GHOST_TYPES)]
    for claim, row in census["ghosts_by_reported_status"].items():
        out.append(f"| {claim} | " + " | ".join(str(row[t]) for t in GHOST_TYPES) + " |")
    out += ["", f"## Five random false-COMPLETE cases (seed {args.seed})", "",
            f"Drawn with `random.Random({args.seed}).sample(population, {PICKS})` from the {len(population)} false-COMPLETE "
            f"cases sorted by case number: {', '.join(picks)}. Emails are masked; every evidence id is a "
            "participant-visible file_id or activity_id. The same walkthrough is available live with "
            "`python code/main.py investigate --case <id>`.", ""]
    builder = CardBuilder(engine)
    for cid in picks:
        out += [f"### {cid}", "", "```text", *walkthrough(engine, results, cid, builder), "```", ""]
    path = CODE_DIR / "docs" / "GHOST_HUNT.md"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"seed {args.seed}: picks {picks}; wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
